"""Closeout audit fails on evidence, source, lock and success-claim tampering."""
import copy
import hashlib
import json
from pathlib import Path
import tempfile
import unittest
from m4_database_closeout import ROOT,MANIFEST,audit as live_audit,production_sources
from unittest.mock import patch


def audit(manifest,**kwargs):
    # Later features may change live M3 code. The completed Database checkpoint
    # stays bound to its retained production snapshot; explicit test overrides
    # still exercise refusal of unexpected/changed inventories.
    if 'production' not in kwargs and 'root' not in kwargs:
        expected=json.loads((ROOT/MANIFEST).read_text())['qualified_production_sha256']
        folder=ROOT/'docs/evidence/m4-database-final-qualified/production'
        actual={name:hashlib.sha256((folder/name).read_bytes()).hexdigest() for name in expected}
        assert actual==expected,'Completed Database production snapshot changed'
        kwargs['production']=actual
    return live_audit(manifest,**kwargs)


class CloseoutAuditTests(unittest.TestCase):
    def test_real_retained_evidence_and_source_bindings_pass(self):
        result=audit(json.loads((ROOT/MANIFEST).read_text()))
        self.assertEqual(result['protected_identities'],324)
        self.assertEqual(result['real_dictionary_records'],6148)

    def test_tampering_cannot_close_milestone(self):
        original=json.loads((ROOT/MANIFEST).read_text())
        for kind in ['evidence','lock','production','protected','escape']:
            m=copy.deepcopy(original)
            if kind=='evidence':m['evidence_sha256'][next(iter(m['evidence_sha256']))]='0'*64
            elif kind=='lock':m['locks_sha256'][next(iter(m['locks_sha256']))]='0'*64
            elif kind=='production':m['qualified_production_sha256']['m3/invented.rs']='0'*64
            elif kind=='protected':m['protected_source_sha256'].pop(next(iter(m['protected_source_sha256'])))
            else:m['evidence_sha256']['../outside']='0'*64
            with self.subTest(kind=kind),self.assertRaises(AssertionError):audit(m)

    def test_consistently_rehashed_partial_report_is_not_real_success(self):
        original=json.loads((ROOT/MANIFEST).read_text())
        report=json.loads((ROOT/original['qualified_source_report']).read_text())
        report['status']='sizing_passed_real_input_refused_choose_supported_dictionary'
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);(root/'report.json').write_text(json.dumps(report));(root/'lock').write_bytes(b'lock')
            h=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
            m={'evidence_sha256':{'report.json':h(root/'report.json')},'locks_sha256':{'lock':h(root/'lock')},
               'qualified_source_report':'report.json','qualified_production_sha256':{},'protected_source_sha256':{}}
            with self.assertRaises(AssertionError):audit(m,root=root,production={},protected={})

    def test_known_nested_archive_is_not_a_build_source_but_new_real_sources_are(self):
        with patch('m4_database_closeout.sources',return_value={'m3/native-adapter/src/lib.rs':'a','m3/desktop/mdict-studio-m0-m1/old.rs':'b','m3/native-adapter/src/new.rs':'c'}):
            self.assertEqual(production_sources(),{'m3/native-adapter/src/lib.rs':'a','m3/native-adapter/src/new.rs':'c'})

    def test_only_exact_previously_qualified_platform_files_are_optional(self):
        m=json.loads((ROOT/MANIFEST).read_text());bindings=json.loads((ROOT/m['optional_platform_bindings']).read_text())
        production=dict(m['qualified_production_sha256'])
        for name,item in bindings['files'].items():production[name]=item['sha256']
        result=audit(m,production=production)
        self.assertEqual(set(result['optional_platform_files_verified']),set(bindings['files']))
        for name in bindings['files']:
            bad=dict(production);bad[name]='0'*64
            with self.subTest(name=name),self.assertRaises(AssertionError):audit(m,production=bad)
        production['m3/desktop/src-tauri/permissions/autogenerated/unexpected.toml']='0'*64
        with self.assertRaisesRegex(AssertionError,'extra='):audit(m,production=production)

    def test_reviewed_lock_normalization_accepts_only_bound_exact_hashes(self):
        import m4_database_closeout as runner
        m=json.loads((ROOT/MANIFEST).read_text())
        variants=json.loads((ROOT/m['reviewed_lock_normalizations']).read_text())['accepted_sha256']
        original=runner.digest
        resolved={ROOT/name:values[1] for name,values in variants.items()}
        with patch.object(runner,'digest',side_effect=lambda p:resolved.get(p) or original(p)):
            self.assertEqual(audit(m)['status'],'passed')
        for name in variants:
            with self.subTest(name=name),patch.object(runner,'digest',side_effect=lambda p: '0'*64 if p==ROOT/name else original(p)),self.assertRaises(AssertionError):
                audit(m)

    def test_final_decision_preserves_original_failure_and_binds_evidence(self):
        folder=ROOT/'docs/evidence/m4-database-final-qualified'
        decision=json.loads((folder/'decision.json').read_text())
        self.assertTrue(decision['M4_complete'])
        self.assertFalse(decision['production_release_ready'])
        self.assertEqual(decision['accepted_checkpoints'],3)
        for name,h in decision['retained_files_sha256'].items():
            self.assertEqual(hashlib.sha256((folder/name).read_bytes()).hexdigest(),h)
        outer=json.loads((folder/'closeout-report.json').read_text())
        self.assertEqual(outer['status'],'failed')
        self.assertTrue(all(s['returncode']==0 for s in outer['steps']))
        self.assertEqual(decision['current_audit_manifest_sha256'],hashlib.sha256((ROOT/MANIFEST).read_bytes()).hexdigest())
